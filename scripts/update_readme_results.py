"""Replace the README's generated results block with numbers from a compare_runs summary.

  python scripts/update_readme_results.py reports/base/summary.json [reports/finetuned/summary.json ...]

Only touches the text between <!-- RESULTS:START --> and <!-- RESULTS:END -->. No number is typed by hand.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"


def pct(x):
    return "—" if x is None else f"{100 * x:.1f}%"


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    rows = [r for p in sys.argv[1:] for r in json.loads(Path(p).read_text())]
    probes = [r for r in rows if r.get("dataset") == "latency_probe"]
    rows = [r for r in rows if r.get("dataset") != "latency_probe"]
    real = [r for r in rows if r.get("mode") == "LOCAL_MODEL"] or rows
    lines = [START, "", "_Generated by `scripts/update_readme_results.py` from `reports/`. Synthetic team-written tickets; "
             "threshold and gate mode were chosen on the calibration split and locked before scoring._", "",
             "| Run | Dataset | Samples | Category accuracy (95% CI) | Rules-only baseline | Kept on site | Error among kept | "
             "Unsafe accepts | p50 latency | PII leaked | Potential payload bytes per ticket (hybrid / cloud-only) |",
             "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in real:
        ci = f" ({pct(r['category_ci'][0])}–{pct(r['category_ci'][1])})" if r.get("category_ci") else ""
        p50 = f"{r['p50_ms'] / 1000:.1f} s" + (f" ({r['workers']} in flight)" if (r.get("workers") or 1) > 1 else "") if r.get("p50_ms") is not None else "—"
        lines.append(f"| {r['run']} | {r['dataset']} | {r['samples']} | {pct(r['category_accuracy'])}{ci} | {pct(r['rules_baseline'])} | "
                     f"{pct(r['local_rate'])} | {pct(r['selective_error'])} | {r['unsafe_accepts']} | {p50} | "
                     f"{r['pii_leaked']}/{r['pii_planted']} | {r['egress_hybrid_b'] or 0:,.0f} / {r['egress_cloud_only_b'] or 0:,.0f} |")
    for p in probes:
        lines += ["", f"Single-ticket latency (one ticket at a time, n={p['cases']}): p50 {p['p50_ms'] / 1000:.2f} s, p95 {p['p95_ms'] / 1000:.2f} s."]
    if any(r.get("mode") != "LOCAL_MODEL" for r in rows) and real is rows:
        lines += ["", "**These rows are SIMULATION plumbing checks, not model results.**"]
    lines += ["", END]
    readme = ROOT / "README.md"
    text = readme.read_text()
    if START not in text or END not in text:
        sys.exit("README has no results markers")
    before, rest = text.split(START, 1)
    readme.write_text(before + "\n".join(lines) + rest.split(END, 1)[1])
    print(f"README results updated from {len(real)} runs")


if __name__ == "__main__":
    main()
